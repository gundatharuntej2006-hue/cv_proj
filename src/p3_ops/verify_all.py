"""P3 audit runner: runs tests/p3_verify and writes docs/p3_verification_report.md.

    make p3-verify          # = python -m p3_ops.verify_all
    python -m p3_ops.verify_all --only A2 C3     # re-run selected checks; the report keeps the other results

Read-only except the report, artifacts/p3/verify/ and regenerated preview images (G3). Never touches sealed data.
"""
from __future__ import annotations

import argparse
import json
import os
import platform
import shutil
import subprocess
import sys
import tempfile
from datetime import datetime, timezone
from importlib import metadata
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
REPORT = REPO / "docs" / "p3_verification_report.md"
STATE = REPO / "artifacts" / "p3" / "verify" / "results_latest.json"
ORDER = list("ABCDEFGHIJK")
PACKAGES = ("torch", "torchvision", "numpy", "pillow", "pyarrow", "jsonschema", "pycocotools", "faster-coco-eval",
            "transformers", "grad-cam", "reportlab", "pypdf", "pypdfium2", "pytest", "scipy", "matplotlib", "PyYAML")


def severity(check_id: str) -> int:
    """1 = sealed-run discipline and PHI, 2 = contracts / decisions / interfaces, 3 = quality and the rest."""
    if check_id[0] == "H" or check_id == "G4":
        return 1
    if check_id[0] in "BC" or check_id in ("D1", "D2", "D3", "A1", "A4"):
        return 2
    return 3


def run_checks(only: list[str] | None) -> list[dict]:
    tmp = Path(tempfile.mkdtemp(prefix="p3verify_"))
    out = tmp / "results.jsonl"
    args = [sys.executable, "-m", "pytest", "tests/p3_verify", "-p", "no:cacheprovider", "-q", "-rA",
            f"--basetemp={tmp / 'bt'}"]
    if only:
        args += ["-k", " or ".join(f"test_{c}" for c in only)]
    env = {**os.environ, "P3_VERIFY": "1", "P3_VERIFY_OUT": str(out), "PYTHONIOENCODING": "utf-8"}
    subprocess.run(args, cwd=REPO, env=env)
    rows = [json.loads(l) for l in out.read_text(encoding="utf-8").splitlines()] if out.exists() else []
    shutil.rmtree(tmp, ignore_errors=True)
    return rows


def _key(r: dict):
    c = r["id"]
    return ORDER.index(c[0]), int(c[1:])


def _cell(s: str, n: int = 400) -> str:
    s = " ".join(str(s).split())
    return (s[:n] + " ...") if len(s) > n else s


def environment() -> list[str]:
    try:
        sha = subprocess.run(["git", "-C", str(REPO), "rev-parse", "--show-toplevel"], capture_output=True,
                             text=True).stdout.strip()
        sha = "none (cv_proj is not its own git repository)" if Path(sha).resolve() != REPO.resolve() else \
            subprocess.run(["git", "-C", str(REPO), "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
    except OSError:
        sha = "git unavailable"
    vers = []
    for p in PACKAGES:
        try:
            vers.append(f"{p} {metadata.version(p)}")
        except metadata.PackageNotFoundError:
            vers.append(f"{p} (not installed)")
    return [f"- Git SHA: {sha}", f"- Date (UTC): {datetime.now(timezone.utc).isoformat(timespec='seconds')}",
            f"- Python: {platform.python_version()} ({sys.executable})", f"- Platform: {platform.platform()}",
            f"- Packages: {', '.join(vers)}"]


def write_report(rows: list[dict]) -> Path:
    rows = sorted(rows, key=_key)
    counts = {s: sum(r["status"] == s for r in rows) for s in ("PASS", "FAIL", "MANUAL", "NOT_YET")}
    unowned = [r["id"] for r in rows if r["status"] in ("MANUAL", "NOT_YET") and not (r["owner"] and (r["command"] or r["owner"]))]
    ready = counts["FAIL"] == 0 and not unowned
    L = ["# P3 verification report", "",
         "Generated by `make p3-verify` (src/p3_ops/verify_all.py running tests/p3_verify). Statuses: PASS, FAIL, "
         "MANUAL (needs you / a GPU / the guide), NOT_YET (upstream not ready). No sealed data was read and no gate "
         "token was requested.", "",
         "## 1. Summary", "", "| Total | PASS | FAIL | MANUAL | NOT_YET | Verdict |", "|---|---|---|---|---|---|",
         f"| {len(rows)} | {counts['PASS']} | {counts['FAIL']} | {counts['MANUAL']} | {counts['NOT_YET']} | "
         f"**{'READY' if ready else 'NOT READY'}** |", "",
         "READY requires zero FAIL and an owner + command for every MANUAL / NOT_YET item.", "",
         "## 2. All checks", "", "| Check | Description | Status | Evidence | Fix if failing |", "|---|---|---|---|---|"]
    for r in rows:
        L.append(f"| {r['id']} | {r['desc']} | **{r['status']}** | {_cell(r['evidence']).replace('|', '/')} | "
                 f"{_cell(r['fix'], 250).replace('|', '/') if r['status'] == 'FAIL' else ''} |")
    L += ["", "## 3. Blockers (FAIL), most severe first", "",
          "Severity 1 = sealed-run discipline and PHI, 2 = contracts / decisions / interfaces, 3 = quality.", ""]
    fails = sorted((r for r in rows if r["status"] == "FAIL"), key=lambda r: (severity(r["id"]), _key(r)))
    for r in fails or []:
        L += [f"### {r['id']} (severity {severity(r['id'])}): {r['desc']}", "", "Evidence:", "", "```",
              r["evidence"], "```", "", f"Fix: {r['fix']}" + (f" (owner: {r['owner']})" if r["owner"] else ""), ""]
    if not fails:
        L.append("None.")
    L += ["", "## 4. Manual to-do", "", "| Check | Owner | Command / action |", "|---|---|---|"]
    L += [f"| {r['id']} | {r['owner']} | `{r['command']}` |" for r in rows if r["status"] == "MANUAL"]
    L += ["", "## 5. Waiting on others (NOT_YET)", "", "| Check | Responsible | Then |", "|---|---|---|"]
    L += [f"| {r['id']} | {r['owner'] or '?'} | `{r['command']}` |" if r["command"] else
          f"| {r['id']} | {r['owner'] or '?'} | |" for r in rows if r["status"] == "NOT_YET"]
    if any("Recomputed 10" in r["evidence"] for r in rows):
        j3 = next(r for r in rows if r["id"] == "J3")
        L += ["", "## J3 detail: 10 recomputed numbers", "", j3["evidence"].split("Recomputed 10 random numbers:\n", 1)[-1]]
    L += ["", "## Harness notes", "",
          "Before the final run, three false positives in the audit harness itself were fixed (the checks were "
          "wrong, not the P3 code): D3 matched `>= 0.01` inside a docstring; D2 counted `IS_STUB = False` flag lines "
          "as stub markers; G4 applied the 'image file name' pattern to artifact file names/paths that are PNGs by "
          "design. No P3 code was changed during the audit.",
          "", "## 6. Environment", "", *environment(), ""]
    REPORT.write_text("\n".join(L), encoding="utf-8")
    return REPORT


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--only", nargs="*", help="check ids to re-run (others keep their last result)")
    a = ap.parse_args(argv)
    new = run_checks(a.only)
    rows = new
    if a.only and STATE.exists():
        old = {r["id"]: r for r in json.loads(STATE.read_text(encoding="utf-8"))}
        old.update({r["id"]: r for r in new})
        rows = list(old.values())
    STATE.parent.mkdir(parents=True, exist_ok=True)
    STATE.write_text(json.dumps(rows, indent=1), encoding="utf-8")
    p = write_report(rows)
    counts = {s: sum(r["status"] == s for r in rows) for s in ("PASS", "FAIL", "MANUAL", "NOT_YET")}
    print(f"\n{len(rows)} checks: {counts} -> {p}")
    return 1 if counts["FAIL"] else 0


if __name__ == "__main__":
    raise SystemExit(main())
